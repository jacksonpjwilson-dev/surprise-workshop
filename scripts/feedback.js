#!/usr/bin/env node
'use strict';
// Record Jackson's reaction to an invention and refresh the learned section of PREFERENCES.md.
// Usage: node scripts/feedback.js <inventionId> [--rating 1-5] [--note "his words"] [--like tag,tag] [--dislike tag,tag]
//        node scripts/feedback.js --refresh      (only regenerate PREFERENCES.md)
const fs = require('fs');
const { P, history, feedback, preferences, writeJSON, args, die } = require('../lib/common');
const a = args();
const h = history(), fb = feedback();
if (!a.refresh) {
  const id = a._[0]; const inv = h.inventions.find(i => i.id === id);
  if (!inv) die(`Unknown invention id. Known: ${h.inventions.map(i => i.id).join(', ') || '(none)'}`);
  const rating = a.rating === undefined ? null : Number(a.rating);
  if (rating !== null && !(Number.isInteger(rating) && rating >= 1 && rating <= 5)) die('--rating must be an integer 1-5');
  const list = v => (typeof v === 'string' ? v.split(',').map(s => s.trim()).filter(Boolean) : []);
  const entry = { at: new Date().toISOString(), inventionId: id, category: inv.category, rating, note: a.note && a.note !== true ? String(a.note) : '', liked: list(a.like), disliked: list(a.dislike) };
  if (rating === null && !entry.note && !entry.liked.length && !entry.disliked.length) die('Give at least one of --rating, --note, --like, --dislike');
  fb.entries.push(entry); writeJSON(P.feedback, fb);
  if (rating !== null) inv.rating = rating;
  if (entry.note) inv.feedback = entry.note;
  writeJSON(P.history, h);
  console.log(`Recorded feedback for ${id}.`);
}
// Regenerate the AUTO section of PREFERENCES.md (the hand-written part above it is kept).
const prefs = preferences(fb, h);
const cats = Object.entries(prefs.catAvg).sort((x, y) => y[1] - x[1]).map(([c, v]) => `- ${c}: ${v.toFixed(1)} / 5`).join('\n') || '- (no ratings yet)';
const tags = Object.entries(prefs.tagScore).sort((x, y) => y[1] - x[1]);
const liked = tags.filter(([, v]) => v > 0).slice(0, 12).map(([t]) => t).join(', ') || '(none yet)';
const disliked = tags.filter(([, v]) => v < 0).slice(-12).map(([t]) => t).join(', ') || '(none yet)';
const notes = fb.entries.filter(e => e.note).slice(-8).reverse().map(e => `- ${e.at.slice(0, 10)} on ${e.inventionId}: “${e.note.replace(/\n/g, ' ')}”`).join('\n') || '- (none yet)';
const auto = `<!-- AUTO:START (generated by scripts/feedback.js; do not edit by hand) -->
## Learned from feedback (${fb.entries.length} reaction${fb.entries.length === 1 ? '' : 's'})

Average rating by category:
${cats}

Tags he responds well to: ${liked}

Tags to go easy on: ${disliked}

Recent comments:
${notes}
<!-- AUTO:END -->`;
const cur = fs.existsSync(P.prefs) ? fs.readFileSync(P.prefs, 'utf8') : '# Preferences\n\n';
const next = /<!-- AUTO:START[\s\S]*<!-- AUTO:END -->/.test(cur) ? cur.replace(/<!-- AUTO:START[\s\S]*<!-- AUTO:END -->/, auto) : cur.trimEnd() + '\n\n' + auto + '\n';
fs.writeFileSync(P.prefs, next);
console.log('PREFERENCES.md updated.');
